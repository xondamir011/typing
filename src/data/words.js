export const getRandomWords = (language = 'en', count = 50) => {
  const languageWords = words[language] || words.en;
  const result = [];
  for (let i = 0; i < count; i++) {
    const randomIndex = Math.floor(Math.random() * languageWords.length);
    result.push(languageWords[randomIndex]);
  }
  return result.join(" "); 
};

